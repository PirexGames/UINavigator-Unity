using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace PirexGames.Core.UINavigator.Editor
{
    [InitializeOnLoad]
    public static class UINavigatorGenerator
    {
        private const string GENERATED_FILE_PATH = "Assets/PirexGames.Generated/UINavigatorHub.Generated.cs";
        private const string ASMDEF_FILE_PATH = "Assets/PirexGames.Generated/PirexGames.Generated.UINavigator.asmdef";

        private static float _nextGenerateTime = -1f;
        private const float GENERATE_DELAY = 0.1f; // Fast response after Unfocus/Enter

        static UINavigatorGenerator()
        {
            EditorApplication.update += OnUpdate;
            UnityEditor.SceneManagement.EditorSceneManager.sceneSaved += _ => Generate();
            UnityEditor.SceneManagement.PrefabStage.prefabSaved += _ => Generate();
        }

        private static void OnUpdate()
        {
            if (_nextGenerateTime > 0 && (float)EditorApplication.timeSinceStartup > _nextGenerateTime)
            {
                _nextGenerateTime = -1f;
                Generate();
            }
        }

        /// <summary>
        /// Requests a generation with a delay to avoid lag during typing.
        /// </summary>
        public static void RequestGenerate()
        {
            _nextGenerateTime = (float)EditorApplication.timeSinceStartup + GENERATE_DELAY;
        }

        [MenuItem("Tools/PirexGames/UINavigator/Regenerate Hub Accessors")]
        public static void Generate()
        {
            _nextGenerateTime = -1f; // Stop any pending requests
            // Update Directory
            var dir = Path.GetDirectoryName(GENERATED_FILE_PATH);
            if (!Directory.Exists(dir))
            {
                Directory.CreateDirectory(dir);
            }

            // Generate .asmdef if missing
            if (!File.Exists(ASMDEF_FILE_PATH))
            {
                var asmdef = new StringBuilder();
                asmdef.AppendLine("{");
                asmdef.AppendLine("    \"name\": \"PirexGames.Generated\",");
                asmdef.AppendLine("    \"rootNamespace\": \"\",");
                asmdef.AppendLine("    \"references\": [");
                asmdef.AppendLine("        \"PirexGames.Core.UINavigator\",");
                asmdef.AppendLine("        \"UniTask\",");
                asmdef.AppendLine("        \"Unity.Addressables\"");
                asmdef.AppendLine("    ],");
                asmdef.AppendLine("    \"autoReferenced\": true");
                asmdef.AppendLine("}");
                File.WriteAllText(ASMDEF_FILE_PATH, asmdef.ToString(), Encoding.UTF8);
            }
            var containers = FindAllCustomContainers();
            var code = GenerateCode(containers);

            File.WriteAllText(GENERATED_FILE_PATH, code, Encoding.UTF8);
            AssetDatabase.Refresh();
            
            Debug.Log($"[UINavigator] Generated {containers.Count} custom accessors in UINavigatorHub at {GENERATED_FILE_PATH}");
        }

        private static List<UIContainer> FindAllCustomContainers()
        {
            var result = new List<UIContainer>();
            
            // 1. Scan all Prefabs in project
            var guids = AssetDatabase.FindAssets("t:Prefab");
            foreach (var guid in guids)
            {
                var path = AssetDatabase.GUIDToAssetPath(guid);
                var root = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (root == null) continue;

                var containers = root.GetComponentsInChildren<UIContainer>(true);
                foreach (var container in containers)
                {
                    if (container != null && container.NameMode == ContainerNameMode.Custom)
                    {
                        result.Add(container);
                    }
                }
            }

            // 2. Scan active scenes
            var sceneContainers = Object.FindObjectsOfType<UIContainer>(true);
            foreach (var container in sceneContainers)
            {
                if (container.NameMode == ContainerNameMode.Custom)
                {
                    // Check if already added from prefab to avoid duplicates
                    if (result.Any(r => r.ContainerName == container.ContainerName)) continue;
                    result.Add(container);
                }
            }
            
            return result;
        }

        private static string GenerateCode(List<UIContainer> containers)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using PirexGames.Core.UINavigator;");
            sb.AppendLine();
            sb.AppendLine("namespace PirexGames.Core.UINavigator");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary> Project-specific hub for custom UI containers </summary>");
            sb.AppendLine("    public static class UINavigatorHub");
            sb.AppendLine("    {");

            // Avoid duplicates naming
            var processedNames = new HashSet<string>();

            foreach (var container in containers)
            {
                var name = container.ContainerName;
                if (string.IsNullOrEmpty(name) || name == "Default") continue;
                if (processedNames.Contains(name)) continue;

                processedNames.Add(name);
                var type = container.GetType().Name;

                sb.AppendLine($"        /// <summary> Accessor for custom container '{name}' </summary>");
                sb.AppendLine($"        public static {type} {name} => UINavigator.GetContainer<{type}>(\"{name}\");");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }
    }
}
